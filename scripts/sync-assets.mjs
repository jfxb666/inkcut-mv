// Publish the generated footage into the Remotion project and regenerate the asset table
// with ffprobe-measured durations. A shot with no clip falls back to its still plate, so the
// composition stays previewable while the batch is still running.
import { readdirSync, existsSync, writeFileSync, statSync, copyFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { C, assetPath } from "./config.mjs";

const probe = (f) => {
  const out = execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0",
    "-show_entries", "stream=width,height,duration", "-of", "default=nw=1", f], { encoding: "utf8" });
  const get = (k) => Number((out.match(new RegExp(k + "=(.*)")) || [])[1]);
  return { w: get("width"), h: get("height"), dur: get("duration") };
};

mkdirSync(C.publicAssets, { recursive: true });
const ids = existsSync(C.clips)
  ? readdirSync(C.clips).filter((f) => f.endsWith(".mp4")).map((f) => f.slice(0, -4)).sort()
  : [];
const plates = readdirSync(C.publicAssets).filter((f) => /^plate_.*\.png$/.test(f))
  .map((f) => f.slice(6, -4));
const all = [...new Set([...ids, ...plates])].sort();
if (!all.length) {
  console.error("nothing to publish: work/clips/ is empty and there are no plates in " + C.publicAssets);
  process.exit(1);
}

const rows = [];
for (const id of all) {
  const src = join(C.clips, id + ".mp4");
  let clip = "null", dur = 0, w = 0, h = 0;
  if (existsSync(src) && statSync(src).size > 40000) {
    copyFileSync(src, join(C.publicAssets, "clip_" + id + ".mp4"));
    const p = probe(src);
    ({ w, h } = p);
    dur = p.dur;
    clip = JSON.stringify(assetPath(join(C.publicAssets, "clip_" + id + ".mp4")));
  }
  const plate = assetPath(join(C.publicAssets, "plate_" + id + ".png"));
  rows.push(`  ${id}: { id: "${id}", clip: ${clip}, clipDur: ${dur.toFixed(4)}, w: ${w}, h: ${h}, plate: "${plate}" },`);
}

const out = `// AUTO-GENERATED by scripts/sync-assets.mjs - do not edit by hand.
// clip: null means the shot falls back to its still plate (parallax + local motion).
export type ShotAsset = {
  id: string;
  clip: string | null;
  /** Measured duration of the AI clip in seconds; 0 when there is no clip. */
  clipDur: number;
  w: number;
  h: number;
  plate: string;
};

export const SHOT_ASSETS: Record<string, ShotAsset> = {
${rows.join("\n")}
};

export const AUDIO_SRC = "${assetPath(C.audio)}";
`;
writeFileSync(join(C.composeSrc, "shotAssets.ts"), out);
console.log(`published ${all.length} shots -> ${C.composeSrc}/shotAssets.ts`);
console.log(`  with clip: ${ids.join(", ") || "(none)"}`);
console.log(`  plate only: ${all.filter((i) => !ids.includes(i)).join(", ") || "(none)"}`);
